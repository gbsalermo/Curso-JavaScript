/**
 * Aritméticos
 * + Adição /Concatenação quando é String unindo os dois valores
 * - Subtração
 * / Divisão
 * * Multiplicação
 * ** potenciação
 * % Resto da divisão
 * Os operadores tem procedencia: (), **, * / %, + -
 * ++somando ele primeiro incrementa e depois mostra o valor
 * somando++ ele mostra o valor e depois incrementa
 * você pode usar parseInt ou parseFloat, para converter os numeros a inteiros ou flutuantes
 * Da para usar Number tambem, que ai o proprio sistema entende se é inteiro ou float
 */

//Exemplos

let num1 = 10;
let num2 = 5;
let num4 = parseInt('5.2')

console.log(num1 + num2);
console.log(num1 - num2);
console.log(num1 / num2);
console.log(num1 * num2);
console.log( num1 ** num2);
console.log(num1 % num2);
console.log(num1++);
console.log(++num1);
console.log(num1 + num4);

